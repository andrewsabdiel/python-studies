# Exercício de classificação de vallores ( - ou + )
print("---- Olá! Iremos ver se seu número é positivo ou negativo! ----")

Valor = int(input("Insira o seu número: "))

print("-"*40)

if Valor > 0:
    print("O número digitado é positivo.")

elif Valor == 0:
    print("O número digitado é igual à 0.")

else:
    print("O número digitado é negativo.")

print("-"*40)

print("Processo finalizado!")
print("Encerrando...")

